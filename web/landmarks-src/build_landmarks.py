"""Generate web/landmarks.js from icons.py + map.json.

Run from anywhere:  python -I web/landmarks-src/build_landmarks.py
(run build_map.py first if map.json is missing)
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import icons  # noqa: E402

# Real coordinates (2-decimal precision is plenty at map scale).
PLACES = {
    "masmak":    ("Masmak Fortress", "Riyadh", 24.63, 46.71),
    "kingdom":   ("Kingdom Centre", "Riyadh", 24.71, 46.67),
    "wadi":      ("Wadi Hanifa", "Riyadh", 24.66, 46.60),
    "turaif":    ("At-Turaif", "Diriyah", 24.73, 46.57),
    "edge":      ("Edge of the World", "Jebel Fihrayn", 24.95, 45.99),
    "ushaiqer":  ("Ushaiqer Heritage Village", "Shaqra", 25.34, 45.18),
    "buraydah":  ("Buraydah", "Al-Qassim", 26.33, 43.97),
    "hail":      ("Jubbah rock art & Aja mountains", "Hail", 27.52, 41.69),
    "alula":     ("Elephant Rock (Jabal AlFil)", "AlUla", 26.69, 37.98),
    "hegra":     ("Hegra (Mada'in Salih)", "AlUla", 26.79, 37.95),
    "balad":     ("Al-Balad", "Jeddah", 21.48, 39.19),
    "fountain":  ("King Fahd's Fountain", "Jeddah", 21.51, 39.15),
    "jtower":    ("Jeddah Corniche", "Jeddah", 21.60, 39.11),
    "dammam":    ("Dammam Corniche", "Dammam", 26.44, 50.11),
    "murabba":   ("Al Murabba Palace", "Riyadh", 24.65, 46.71),
    "museum":    ("National Museum", "Riyadh", 24.65, 46.71),
    "boulevard": ("Riyadh Boulevard", "Riyadh", 24.77, 46.60),
    "taif":      ("Taif rose fields", "Taif", 21.27, 40.42),
    "abha":      ("Abha", "Asir", 18.22, 42.51),
}


def main():
    m = json.load(open(os.path.join(HERE, "map.json"), encoding="utf-8"))
    p = m["projection"]
    icon_js = ",\n".join(f"    {k}: {json.dumps(icons.svg(k, PLACES[k][0] if k in PLACES else None))}"
                         for k in icons.NAMES)
    places_js = ",\n".join(
        f'    {k}: {{name: {json.dumps(n)}, city: {json.dumps(c)}, lat: {lat}, lon: {lon}}}'
        for k, (n, c, lat, lon) in PLACES.items())
    js = f"""/* Walk across Saudi Arabia: landmark icons + map. GENERATED by web/landmarks-src/build_landmarks.py, do not edit by hand.
   Icons: original illustrations (96x96, Playful Bold palette).
   Map: {m["source"]}, simplified.
   Projection: equirectangular, {p["formula"]}
               lon0={p["lon0"]}, lat0={p["lat0"]}, cosLat=cos({p["standardParallel"]} deg)={p["cosLat"]}, scale={p["scale"]}, ox={p["ox"]}, oy={p["oy"]} */
(function () {{
  var LON0 = {p["lon0"]}, LAT0 = {p["lat0"]}, COSLAT = {p["cosLat"]}, S = {p["scale"]}, OX = {p["ox"]}, OY = {p["oy"]};
  window.WalkLandmarks = {{
  icons: {{
{icon_js}
  }},
  map: {{
    viewBox: {json.dumps(m["viewBox"])},
    saudi: {json.dumps(m["saudi"])},
    neighbors: {json.dumps(m["neighbors"])},
    projection: {{type: "equirectangular", lon0: LON0, lat0: LAT0, cosLat: COSLAT, scale: S, ox: OX, oy: OY}},
    project: function (lat, lon) {{
      return [OX + (lon - LON0) * COSLAT * S, OY + (LAT0 - lat) * S];
    }}
  }},
  places: {{
{places_js}
  }}
  }};
}})();
"""
    out = os.path.join(HERE, "..", "landmarks.js")
    open(out, "w", encoding="utf-8", newline="\n").write(js)
    print("wrote", os.path.normpath(out), len(js.encode()), "bytes")
    for k in icons.NAMES:
        print(f"  {k:10s} {len(icons.svg(k)):5d} B")


if __name__ == "__main__":
    main()
